// 既存の自由記述カテゴリ列（parentCategory/subCategory/detailCategory、非推奨）を、
// 新しい固定33ジャンル体系（primaryGenreId/secondaryGenreIds/informationTypes）から
// 後方互換のために自動生成する。既存UI・既存カラムを壊さないための橋渡し関数。
export function deriveLegacyCategoryFields(
  primaryGenreId: string,
  secondaryGenreIds: string[],
  informationTypes: string[],
): { parentCategory: string; subCategory: string; detailCategory: string } {
  const primaryConfig = getGenreConfig(primaryGenreId);
  const secondaryConfig = secondaryGenreIds.length > 0 ? getGenreConfig(secondaryGenreIds[0]) : undefined;

  return {
    parentCategory: primaryConfig?.displayName ?? "未分類",
    subCategory: secondaryConfig?.displayName ?? primaryConfig?.displayName ?? "未分類",
    detailCategory: informationTypes.length > 0 ? informationTypes.join("・") : "詳細未分類",
  };
}
