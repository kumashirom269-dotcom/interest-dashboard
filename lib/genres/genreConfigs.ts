interface StandardGenreParams {
  genreId: string;
  genreNumber: number;
  displayName: string;
  description: string;
  targetScope: string[];
  tier1ExampleSources: string[];
  tier2ExampleSources: string[];
  tier3ExampleSources: string[];
  informationTypePriorities: string[];
  normalizationKeys: string[];
  crossGenreInformationTypeHints: string[];
  qualitySpecificRules: string[];
  defaultRiskLevel?: RiskLevel;
  officialVerificationRequired?: boolean;
  minimumIndependentSources?: number;
  scoringWeightOverrides?: Partial<GenreScoringWeights>;
  freshnessRules?: GenreFreshnessRule[];
  requiredFactFields?: string[];
  preferredCardTypes?: string[];
}

// ジャンル1〜26の共通ボイラープレート（三層構造の用途区分・標準鮮度テーブル・
// 除外ルール前半4項目）を適用しつつ、ジャンル固有の情報を差し込むビルダー。
function buildStandardGenreConfig(params: StandardGenreParams): GenreDetailedConfig {
  return {
    genreId: params.genreId,
    genreNumber: params.genreNumber,
    displayName: params.displayName,
    aliases: [],
    description: params.description,
    targetScope: params.targetScope,
    sourceLayers: {
      tier1: {
        purposes: TIER1_PURPOSES,
        sourceCategories: ["公式主体", "関係者・主催者公式"],
        exampleSources: params.tier1ExampleSources,
        allowedUses: TIER1_ALLOWED_USES,
        prohibitedUses: TIER1_PROHIBITED_USES,
      },
      tier2: {
        purposes: TIER2_PURPOSES,
        sourceCategories: ["中心専門媒体", "分野別媒体"],
        exampleSources: params.tier2ExampleSources,
        allowedUses: TIER2_ALLOWED_USES,
        prohibitedUses: TIER2_PROHIBITED_USES,
      },
      tier3: {
        purposes: TIER3_PURPOSES,
        sourceCategories: ["主要プラットフォーム", "SNS・コミュニティ"],
        exampleSources: params.tier3ExampleSources,
        allowedUses: TIER3_ALLOWED_USES,
        prohibitedUses: TIER3_PROHIBITED_USES,
      },
    },
    informationTypePriorities: params.informationTypePriorities,
    normalizationKeys: params.normalizationKeys,
    freshnessRules: params.freshnessRules ?? STANDARD_FRESHNESS_RULES,
    crossGenreInformationTypeHints: params.crossGenreInformationTypeHints,
    qualityAndSafetyRules: [...STANDARD_QUALITY_RULES_PREFIX, ...params.qualitySpecificRules],
    requiredFactFields: params.requiredFactFields ?? ["公式発表日時", "対象", "現在有効か"],
    preferredCardTypes: params.preferredCardTypes ?? ["official_announcement"],
    defaultRiskLevel: params.defaultRiskLevel ?? "normal",
    officialVerificationRequired: params.officialVerificationRequired ?? false,
    minimumIndependentSources: params.minimumIndependentSources ?? 1,
    scoringWeights: scoringWeights(params.scoringWeightOverrides),
    configurationVersion: 1,
    lastVerifiedAt: IMPLEMENTATION_DATE,
  };
}

